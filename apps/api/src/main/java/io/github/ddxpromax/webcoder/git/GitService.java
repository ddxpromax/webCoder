package io.github.ddxpromax.webcoder.git;

import io.github.ddxpromax.webcoder.agent.WorkspaceMutationGate;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import org.eclipse.jgit.api.Git;
import org.eclipse.jgit.api.Status;
import org.eclipse.jgit.api.errors.GitAPIException;
import org.eclipse.jgit.diff.DiffEntry;
import org.eclipse.jgit.lib.Constants;
import org.eclipse.jgit.lib.ObjectId;
import org.eclipse.jgit.lib.Repository;
import org.eclipse.jgit.revwalk.RevCommit;
import org.eclipse.jgit.revwalk.RevWalk;
import org.eclipse.jgit.storage.file.FileRepositoryBuilder;
import org.eclipse.jgit.treewalk.CanonicalTreeParser;
import org.springframework.stereotype.Service;

/** Majo's repository lifecycle and version-control API, backed by JGit. */
@Service
public class GitService {
    private static final String DEFAULT_GITIGNORE = """
        # Auto-generated by Majo Coding Mode

        # Python artefacts
        __pycache__/
        *.py[cod]
        *.egg-info/
        .venv/
        venv/
        env/
        .env

        # JS / build artefacts
        node_modules/
        dist/
        build/

        # OS
        .DS_Store

        # Majo runtime / internal directories
        data/
        sessions/
        missions/
        memory/
        browser/
        backup/
        skills/
        *.lock
        """;

    private final WorkspaceMutationGate mutationGate;

    public GitService(WorkspaceMutationGate mutationGate) {
        this.mutationGate = mutationGate;
    }

    /** Creates a repository only when the workspace itself is not a repository. */
    public Path ensureRepo(Path directory) throws IOException {
        Path workspace = directory.toAbsolutePath().normalize();
        if (!isOwnRepository(workspace)) {
            try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(workspace)) {
                if (!isOwnRepository(workspace)) {
                    initialize(workspace);
                }
            }
        }
        return workspace;
    }

    public Map<String, Object> status(Path directory)
        throws IOException, GitAPIException {
        Path workspace = ensureRepo(directory);
        try (Repository repository = openRepo(workspace); Git git = new Git(repository)) {
            Status current = git.status().call();
            List<Map<String, Object>> changes = new ArrayList<>();
            current.getAdded().forEach(path -> changes.add(change(path, "A", true)));
            current.getChanged().forEach(path -> changes.add(change(path, "M", true)));
            current.getRemoved().forEach(path -> changes.add(change(path, "D", true)));
            current.getModified().forEach(path -> changes.add(change(path, "M", false)));
            current.getMissing().forEach(path -> changes.add(change(path, "D", false)));
            current.getUntracked().forEach(path -> changes.add(change(path, "?", false)));
            Map<String, Object> result = new LinkedHashMap<>();
            result.put("branch", branchName(repository));
            result.put("changes", changes);
            result.put("ahead", 0);
            result.put("behind", 0);
            return result;
        }
    }

    public List<Map<String, Object>> branches(Path directory)
        throws IOException, GitAPIException {
        try (Repository repository = openRepo(directory); Git git = new Git(repository)) {
            String current = branchName(repository);
            List<Map<String, Object>> result = new ArrayList<>();
            for (var reference : git.branchList().call()) {
                String name = reference.getName().replace(Constants.R_HEADS, "");
                result.add(Map.of("name", name, "current", name.equals(current),
                    "remote", false));
            }
            return result;
        }
    }

    public Map<String, Object> checkout(Path directory, String branch, boolean create)
        throws IOException, GitAPIException {
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            if (create) {
                git.checkout().setCreateBranch(true).setName(branch).call();
            } else {
                git.checkout().setName(branch).call();
            }
            return Map.of("branch", branch);
        }
    }

    public Map<String, Object> diff(
        Path directory, String path, boolean staged, boolean untracked
    ) throws IOException, GitAPIException {
        try (Repository repository = openRepo(directory); Git git = new Git(repository)) {
            if (untracked && path != null && !path.isBlank()) {
                return Map.of("diff", untrackedDiff(directory, path));
            }
            ByteArrayOutputStream output = new ByteArrayOutputStream();
            git.diff().setCached(staged).setOutputStream(output).call();
            return Map.of("diff", output.toString(StandardCharsets.UTF_8));
        }
    }

    public Map<String, Object> stage(Path directory, List<String> paths)
        throws IOException, GitAPIException {
        List<String> targets = targets(paths);
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            for (String path : targets) {
                git.add().addFilepattern(path).call();
            }
            return Map.of("staged", targets);
        }
    }

    public Map<String, Object> unstage(Path directory, List<String> paths)
        throws IOException, GitAPIException {
        List<String> targets = targets(paths);
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            for (String path : targets) {
                git.reset().addPath(path).call();
            }
            return Map.of("unstaged", targets);
        }
    }

    public Map<String, Object> commit(Path directory, String message)
        throws IOException, GitAPIException {
        if (message == null || message.isBlank()) {
            throw new IllegalArgumentException("Commit message cannot be empty");
        }
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            ObjectId revision = git.commit().setMessage(message.trim()).call();
            return Map.of("committed", true, "output", revision.name());
        }
    }

    public Map<String, Object> revert(Path directory, String commitHash)
        throws IOException, GitAPIException {
        if (commitHash == null || commitHash.isBlank()) {
            throw new IllegalArgumentException("commit_hash is required");
        }
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            ObjectId id = git.getRepository().resolve(commitHash);
            if (id == null) {
                throw new IllegalArgumentException("Unknown commit: " + commitHash);
            }
            RevCommit revision = git.revert().include(id).call();
            if (revision == null) {
                throw new IllegalArgumentException("Revert failed (conflict?): " + commitHash);
            }
            String shortName = revision.name().substring(0, Math.min(7, revision.name().length()));
            return Map.of("reverted", commitHash, "output",
                "[master " + shortName + "] Revert \"" + commitHash + "\"");
        }
    }

    public Map<String, Object> discard(Path directory, List<String> paths)
        throws IOException, GitAPIException {
        List<String> targets = targets(paths);
        try (WorkspaceMutationGate.Lease ignored = mutationGate.acquire(directory);
             Git git = new Git(openRepo(directory))) {
            for (String path : targets) {
                git.checkout().addPath(path).call();
            }
            git.clean().setForce(true).setIgnore(false)
                .setPaths(new LinkedHashSet<>(targets)).call();
            return Map.of("discarded", targets);
        }
    }

    public Map<String, Object> commitDiff(Path directory, String hash)
        throws IOException, GitAPIException {
        try (Repository repository = openRepo(directory); RevWalk walk = new RevWalk(repository)) {
            ObjectId id = repository.resolve(hash);
            if (id == null) {
                throw new IllegalArgumentException("Unknown commit: " + hash);
            }
            RevCommit commit = walk.parseCommit(id);
            ByteArrayOutputStream output = new ByteArrayOutputStream();
            CanonicalTreeParser oldTree = new CanonicalTreeParser();
            CanonicalTreeParser newTree = new CanonicalTreeParser();
            try (var reader = repository.newObjectReader()) {
                if (commit.getParentCount() == 0) {
                    oldTree.reset(reader, Constants.EMPTY_TREE_ID);
                } else {
                    oldTree.reset(reader, walk.parseTree(commit.getParent(0)).getId());
                }
                newTree.reset(reader, commit.getTree().getId());
            }
            try (Git git = new Git(repository)) {
                List<DiffEntry> entries = git.diff().setOutputStream(output)
                    .setOldTree(oldTree).setNewTree(newTree).call();
                return Map.of("diff", "diff --git " + hash + " ("
                    + entries.size() + " files)\n" + output.toString(StandardCharsets.UTF_8),
                    "hash", hash);
            }
        }
    }

    public List<Map<String, Object>> log(Path directory, int limit)
        throws IOException, GitAPIException {
        try (Repository repository = openRepo(directory); Git git = new Git(repository)) {
            int count = limit <= 0 ? 20 : Math.min(limit, 100);
            List<Map<String, Object>> commits = new ArrayList<>();
            for (RevCommit revision : git.log().setMaxCount(count).call()) {
                Map<String, Object> entry = new LinkedHashMap<>();
                entry.put("hash", revision.getName().substring(0, 8));
                entry.put("author", revision.getAuthorIdent().getName());
                entry.put("date", revision.getAuthorIdent().getWhen().toInstant().toString()
                    .substring(0, 10));
                entry.put("message", revision.getFullMessage().trim());
                commits.add(entry);
            }
            return commits;
        }
    }

    private Repository openRepo(Path directory) throws IOException {
        FileRepositoryBuilder builder = new FileRepositoryBuilder()
            .findGitDir(directory.toFile());
        if (builder.getGitDir() == null) {
            throw new IOException("Not a git repository: " + directory);
        }
        return builder.build();
    }

    private boolean isOwnRepository(Path directory) {
        try {
            FileRepositoryBuilder builder = new FileRepositoryBuilder()
                .findGitDir(directory.toFile());
            return builder.getGitDir() != null && builder.getGitDir().toPath()
                .toAbsolutePath().normalize().equals(directory.resolve(".git")
                    .toAbsolutePath().normalize());
        } catch (Exception ignored) {
            return false;
        }
    }

    private void initialize(Path directory) throws IOException {
        try {
            Files.createDirectories(directory);
            try (Git git = Git.init().setDirectory(directory.toFile()).call()) {
                Path ignore = directory.resolve(".gitignore");
                if (!Files.isRegularFile(ignore)) {
                    Files.writeString(ignore, DEFAULT_GITIGNORE, StandardCharsets.UTF_8);
                }
                git.add().addFilepattern(".").call();
                git.commit().setAuthor("Majo", "majo@localhost")
                    .setMessage("Initial commit").setAllowEmpty(true).call();
            }
        } catch (GitAPIException exception) {
            throw new IOException("git init failed: " + exception.getMessage(), exception);
        }
    }

    private String branchName(Repository repository) throws IOException {
        String branch = repository.getBranch();
        return branch == null || branch.isBlank() ? "HEAD" : branch;
    }

    private Map<String, Object> change(String path, String status, boolean staged) {
        return Map.of("path", path, "status", status, "staged", staged);
    }

    private List<String> targets(List<String> paths) {
        return paths == null || paths.isEmpty() ? List.of(".") : paths;
    }

    private String untrackedDiff(Path directory, String path) throws IOException {
        Path root = directory.toAbsolutePath().normalize();
        Path target = root.resolve(path).normalize();
        if (!target.startsWith(root) || !Files.isRegularFile(target)) {
            return "";
        }
        String content = Files.readString(target, StandardCharsets.UTF_8);
        String additions = content.lines().map(line -> "+" + line)
            .reduce((left, right) -> left + "\n" + right).orElse("");
        return "diff --git a/" + path + " b/" + path + "\n"
            + "new file mode 100644\n--- /dev/null\n+++ b/" + path + "\n"
            + "@@ -0,0 +1," + content.lines().count() + " @@\n"
            + additions + "\n";
    }
}
